/**
 * Build-time script: fetches real GitHub contribution data via GraphQL API.
 * Writes to src/features/contribution-visual/contribution-data.ts
 *
 * Requires GH_CONTRIBUTIONS_TOKEN env var (a GitHub PAT with read:user scope).
 * If the token is missing, the script exits silently — existing data is preserved.
 *
 * Usage:
 *   GH_CONTRIBUTIONS_TOKEN=ghp_xxx node scripts/fetch-contributions.mjs
 */

import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUTPUT_PATH = resolve(__dirname, '../src/features/contribution-visual/contribution-data.ts')

const GITHUB_USERNAME = 'qwewhy'
const GITHUB_GRAPHQL = 'https://api.github.com/graphql'
const TOKEN = process.env.GH_CONTRIBUTIONS_TOKEN

if (!TOKEN) {
  console.log('[fetch-contributions] No GH_CONTRIBUTIONS_TOKEN set — skipping. Existing data preserved.')
  process.exit(0)
}

/**
 * Fetch one year of contribution data from GitHub GraphQL API.
 * @param {string} from  ISO date string (start of year)
 * @param {string} to    ISO date string (end of year)
 * @returns {Promise<{weeks: Array<{contributionDays: Array<{contributionCount: number, date: string}>}>} | null>}
 */
async function fetchYear(from, to) {
  const query = `
    query($login: String!, $from: DateTime!, $to: DateTime!) {
      user(login: $login) {
        contributionsCollection(from: $from, to: $to) {
          contributionCalendar {
            totalContributions
            weeks {
              contributionDays {
                contributionCount
                date
              }
            }
          }
        }
      }
    }
  `

  const res = await fetch(GITHUB_GRAPHQL, {
    method: 'POST',
    headers: {
      Authorization: `bearer ${TOKEN}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      query,
      variables: {
        login: GITHUB_USERNAME,
        from,
        to,
      },
    }),
  })

  if (!res.ok) {
    console.error(`[fetch-contributions] GitHub API error: ${res.status} ${res.statusText}`)
    return null
  }

  const json = await res.json()

  if (json.errors) {
    console.error('[fetch-contributions] GraphQL errors:', json.errors)
    return null
  }

  return json.data.user.contributionsCollection.contributionCalendar
}

/**
 * Map raw contribution counts to intensity levels 0-3.
 * Uses quartile-based thresholds from the non-zero values.
 */
function countsToLevels(counts) {
  const nonZero = counts.filter((c) => c > 0).sort((a, b) => a - b)
  if (nonZero.length === 0) return counts.map(() => 0)

  const q1 = nonZero[Math.floor(nonZero.length * 0.25)]
  const q2 = nonZero[Math.floor(nonZero.length * 0.5)]
  const q3 = nonZero[Math.floor(nonZero.length * 0.75)]

  return counts.map((c) => {
    if (c === 0) return 0
    if (c <= q1) return 1
    if (c <= q2) return 2
    return 3
  })
}

/**
 * Convert calendar data into a flat column-first array (week by week, Mon-Sun).
 * Each year has 52 weeks x 7 days = 364 cells.
 */
function calendarToGrid(calendar) {
  const weeks = calendar.weeks
  const cells = []

  for (const week of weeks) {
    // GitHub returns Sun-Sat, we need Mon-Sun
    const days = week.contributionDays
    // Reorder: Mon(1), Tue(2), Wed(3), Thu(4), Fri(5), Sat(6), Sun(0)
    const reordered = [...days.slice(1), days[0]]
    for (const day of reordered) {
      cells.push(day.contributionCount)
    }
  }

  // Pad or trim to exactly 364 (52 weeks * 7 days)
  const TARGET = 52 * 7
  if (cells.length < TARGET) {
    while (cells.length < TARGET) cells.push(0)
  } else if (cells.length > TARGET) {
    cells.length = TARGET
  }

  return cells
}

async function main() {
  const now = new Date()
  const currentYear = now.getFullYear()
  const years = [currentYear - 1, currentYear]

  const results = {}
  const totals = {}

  for (const year of years) {
    const from = `${year}-01-01T00:00:00Z`
    const to = `${year}-12-31T23:59:59Z`

    console.log(`[fetch-contributions] Fetching ${year}...`)
    const calendar = await fetchYear(from, to)

    if (!calendar) {
      console.error(`[fetch-contributions] Failed to fetch ${year} — aborting. Existing data preserved.`)
      process.exit(0)
    }

    const rawCounts = calendarToGrid(calendar)
    const levels = countsToLevels(rawCounts)

    results[year] = levels
    totals[year] = calendar.totalContributions
  }

  // Generate TypeScript file
  const lines = [
    '// AUTO-GENERATED by scripts/fetch-contributions.mjs — do not edit manually.',
    `// Last updated: ${now.toISOString()}`,
    '',
    'export const contributionData: Record<string, number[]> = {',
  ]

  for (const year of years) {
    const arr = results[year]
    // Format as rows of 7 (one week per line) for readability
    const weekLines = []
    for (let i = 0; i < arr.length; i += 7) {
      weekLines.push(`    ${JSON.stringify(arr.slice(i, i + 7)).slice(1, -1)}`)
    }
    lines.push(`  '${year}': [`)
    lines.push(weekLines.join(',\n') + ',')
    lines.push('  ],')
  }

  lines.push('}')
  lines.push('')
  lines.push("export const monthLabels = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']")
  lines.push('')
  lines.push('export const contributionTotals: Record<string, number> = {')
  for (const year of years) {
    lines.push(`  '${year}': ${totals[year]},`)
  }
  lines.push('}')
  lines.push('')

  writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf-8')
  console.log(`[fetch-contributions] Wrote ${OUTPUT_PATH}`)
  for (const year of years) {
    console.log(`  ${year}: ${totals[year]} contributions`)
  }
}

main().catch((err) => {
  console.error('[fetch-contributions] Unexpected error:', err)
  // Don't fail the build — just preserve existing data
  process.exit(0)
})
